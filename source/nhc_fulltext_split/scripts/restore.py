def _where(spec):
    if spec is None:
        return None, None
    kind, vals = spec.split(':', 1)
    vals = set(vals.split())
    return (vals, None) if kind == 'u' else (None, vals)

_COMPILED = []
for restored, lb, la, conf, spec, note in RULES:
    d = dele(restored)
    assert d and d != restored, restored
    us, rs = _where(spec)
    _COMPILED.append((re.compile(lb + '(' + re.escape(d) + ')' + la), d, restored, conf, us, rs, note))
for d, restored, conf, spec, note in SPECIAL:
    us, rs = _where(spec)
    _COMPILED.append((re.compile('(' + re.escape(d) + ')'), d, restored, conf, us, rs, note))

def _insertions(d, restored, start):
    """d を restored にするために入れる字と位置（d 内の位置 + start）"""
    ins, j = [], 0
    for ch in restored:
        if j < len(d) and ch == d[j]:
            j += 1
        else:
            ins.append((start + j, ch))
    assert j == len(d), (d, restored)
    return ins

def find(items, sid, unit):
    """items: トークン列（GAP と DROP を含む）。当たった規則を重なりなしで返す:
    [(flat 上の開始, 終了, d, restored, conf, note)] と、flat・offs"""
    offs, parts, s = [], [], 0
    for t in items:
        offs.append(s)
        f = BAR if t in (GAP, DROP) else t
        parts.append(f); s += len(f)
    offs.append(s)
    flat = ''.join(parts)
    hits = []
    for rx, d, restored, conf, us, rs, note in _COMPILED:
        if (us is not None and unit not in us) or (rs is not None and sid not in rs):
            continue
        for m in rx.finditer(flat):
            hits.append((m.start(1), m.end(1), d, restored, conf, note))
    hits.sort(key=lambda h: (-(h[1] - h[0]), h[0]))
    taken = []
    for h in hits:
        if all(h[1] <= t[0] or h[0] >= t[1] for t in taken):
            taken.append(h)
    taken.sort()
    return taken, flat, offs

def apply(items, sid, unit):
    """戻した結果のトークン列と、変更の一覧を返す。
    語の途中で切れていたトークンは 1 つにつなぐ（戻した語の前後の切れ目は変えない）。
    変更: (i0, i1, 新しいトークン, [(restored, conf, note)], 入れた字)  ※ i0..i1 は items の添字（両端を含む）"""
    taken, flat, offs = find(items, sid, unit)
    if not taken:
        return list(items), []
    def tok_at(p):          # flat 上の位置 p を含むトークン
        lo, hi = 0, len(items) - 1
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if offs[mid] <= p: lo = mid
            else: hi = mid - 1
        return lo
    groups = []             # [i0, i1, [hits]]
    for h in taken:
        i0, i1 = tok_at(h[0]), tok_at(h[1] - 1)
        if groups and i0 <= groups[-1][1]:
            groups[-1][1] = max(groups[-1][1], i1); groups[-1][2].append(h)
        else:
            groups.append([i0, i1, [h]])
    out, events, pos = [], [], 0
    for i0, i1, hs in groups:
        out.extend(items[pos:i0])
        a, b = offs[i0], offs[i1 + 1]
        seg = flat[a:b]
        assert BAR not in seg
        # 位置だけで並べる（安定ソート）。同じ位置に入る字は、語の中での順のまま（ⲧⲭⲏ → ⲧⲯⲩⲭⲏ の ⲯⲩ など）
        ins = sorted(((p - a, ch) for h in hs for (p, ch) in _insertions(h[2], h[3], h[0])), key=lambda x: x[0])
        new, last = [], 0
        for p, ch in ins:
            new.append(seg[last:p]); new.append(ch); last = p
        new.append(seg[last:])
        new = ''.join(new)
        events.append((i0, i1, new, [(h[3], h[4], h[5]) for h in hs], ''.join(ch for _, ch in ins)))
        out.append(new)
        pos = i1 + 1
    out.extend(items[pos:])
    return out, events
